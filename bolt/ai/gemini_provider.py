"""Google Gemini AI Provider for BOLT."""

import json
from typing import Any, Dict, List, Optional
import requests

from bolt.ai.base import AIProvider, AIResponse, ChatMessage
from bolt.core.logger import get_logger

logger = get_logger("GeminiProvider")

GEMINI_API_BASE = "https://generativelanguage.googleapis.com/v1beta/models"


class GeminiProvider(AIProvider):
    def __init__(self, api_key: str, model: str = "gemini-2.5-flash"):
        self.api_key = api_key.strip()
        self.model = model.strip() or "gemini-2.5-flash"

    @property
    def provider_name(self) -> str:
        return "gemini"

    def _build_contents(self, messages: List[ChatMessage]) -> List[Dict[str, Any]]:
        """Convert chat messages into Gemini API contents structure, ensuring valid turns."""
        contents: List[Dict[str, Any]] = []
        for msg in messages:
            if msg.role == "system":
                # System messages are passed separately via systemInstruction
                continue
            gemini_role = "user" if msg.role == "user" else "model"
            if contents and contents[-1]["role"] == gemini_role:
                contents[-1]["parts"].append({"text": msg.content})
            else:
                contents.append({
                    "role": gemini_role,
                    "parts": [{"text": msg.content}]
                })

        # Gemini requires the first turn to be 'user'
        if contents and contents[0]["role"] != "user":
            contents.insert(0, {"role": "user", "parts": [{"text": "Hello"}]})

        return contents

    def generate_response(
        self,
        messages: List[ChatMessage],
        system_prompt: Optional[str] = None,
        temperature: float = 0.7,
        max_tokens: int = 2048,
    ) -> AIResponse:
        """Call Gemini generateContent API endpoint."""
        if not self.api_key:
            return AIResponse(
                content="",
                model=self.model,
                success=False,
                error="Gemini API Key is not set. Please configure it in Settings or .env.",
            )

        endpoint = f"{GEMINI_API_BASE}/{self.model}:generateContent?key={self.api_key}"
        headers = {"Content-Type": "application/json"}

        payload: Dict[str, Any] = {
            "contents": self._build_contents(messages),
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": max_tokens,
            },
        }

        if system_prompt:
            payload["systemInstruction"] = {
                "parts": [{"text": system_prompt}]
            }

        try:
            logger.debug(f"Calling Gemini API (model: {self.model})...")
            response = requests.post(
                endpoint,
                headers=headers,
                json=payload,
                timeout=45.0,
            )

            if response.status_code != 200:
                err_detail = response.text
                try:
                    err_json = response.json()
                    err_detail = err_json.get("error", {}).get("message", err_detail)
                except Exception:
                    pass

                logger.error(f"Gemini API returned status {response.status_code}: {err_detail}")
                return AIResponse(
                    content="",
                    model=self.model,
                    success=False,
                    error=f"Gemini API Error ({response.status_code}): {err_detail}",
                )

            data = response.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return AIResponse(
                    content="[No response generated by model]",
                    model=self.model,
                    raw_response=data,
                    success=True,
                )

            candidate = candidates[0]
            parts = candidate.get("content", {}).get("parts", [])
            reply_text = "".join(part.get("text", "") for part in parts)

            tokens_used = 0
            if "usageMetadata" in data:
                tokens_used = data["usageMetadata"].get("totalTokenCount", 0)

            return AIResponse(
                content=reply_text,
                model=self.model,
                tokens_used=tokens_used,
                raw_response=data,
                success=True,
            )

        except requests.exceptions.Timeout:
            logger.error("Gemini API request timed out.")
            return AIResponse(
                content="",
                model=self.model,
                success=False,
                error="Gemini API request timed out after 45 seconds.",
            )
        except requests.exceptions.RequestException as e:
            logger.error(f"Network error calling Gemini API: {e}")
            return AIResponse(
                content="",
                model=self.model,
                success=False,
                error=f"Network error communicating with Gemini API: {e}",
            )
        except Exception as e:
            logger.exception("Unexpected error in GeminiProvider")
            return AIResponse(
                content="",
                model=self.model,
                success=False,
                error=f"Internal error: {e}",
            )

    def test_connection(self) -> bool:
        """Test API key validity by querying available models or a mini ping."""
        if not self.api_key:
            return False
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models?key={self.api_key}"
            res = requests.get(url, timeout=10.0)
            return res.status_code == 200
        except Exception as e:
            logger.warning(f"Gemini test connection failed: {e}")
            return False

